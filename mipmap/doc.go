// Package mipmap 提供大尺寸位图的分块（tiling）与多级缩小图（mipmap pyramid）
// 的生成、缓存与采样能力。整条链路在进程内完成，不依赖外部服务。
//
// 核心语义：
//   - 源图被切分为固定尺寸的 Tile，边缘 Tile 尺寸可小于标准尺寸，
//     任一层全部 Tile 拼接后完整还原该层图像，无缺块、无重叠。
//   - 层级尺寸按 ceil(n/2) 逐级减半，直到 1x1 或达到配置上限。
//   - 下采样使用纯整数运算（预乘 alpha 的 2x2 盒式滤波，边缘复制），
//     结果与分块划分、并行度、生成顺序无关，逐像素确定。
//   - 采样支持跨 Tile、跨层级的双线性/三线性插值与各向异性足迹采样，
//     分块边界处结果与整图采样完全一致，无接缝。
